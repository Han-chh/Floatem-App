#!/usr/bin/env node

/**
 * Generate Vite-tracked imports for every optimized asset. Vite emits these
 * imports under content-hashed filenames, so unchanged resources use the same
 * URL across builds and can safely be cached by browsers.
 */
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const repositoryRoot = resolve(scriptDirectory, '../..')
const source = join(repositoryRoot, 'resources/optimized')
const destination = join(repositoryRoot, 'public/resources/optimized')
const generatedManifest = join(repositoryRoot, 'src/content/optimizedAssetManifest.ts')

if (!existsSync(source)) throw new Error(`Generated resources are missing: ${source}`)

function filesIn(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const file = join(directory, entry.name)
    return entry.isDirectory() ? filesIn(file) : [file]
  })
}

const assets = filesIn(source)
  .map((file) => relative(source, file).split(sep).join('/'))
  .sort((first, second) => first.localeCompare(second))

const entries = assets.map((asset) => {
  const key = `/resources/optimized/${asset}`
  const importPath = `../../resources/optimized/${asset}`
  return `  ${JSON.stringify(key)}: new URL(${JSON.stringify(importPath)}, import.meta.url).href,`
})

mkdirSync(dirname(generatedManifest), { recursive: true })
writeFileSync(generatedManifest, `// Generated by scripts/resource/sync-optimized-resources.js. Do not edit.\nexport const optimizedAssetManifest = {\n${entries.join('\n')}\n} as const\n`)

// Phase 4 used this directory before cache-busting imports were available.
// It contains only generated copies, so removing it prevents Vite from
// publishing duplicate, unhashed resource URLs.
rmSync(destination, { recursive: true, force: true })
console.log(`Generated ${assets.length} Vite-tracked asset imports in ${generatedManifest}`)
